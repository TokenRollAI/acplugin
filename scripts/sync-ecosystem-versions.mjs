import { promises as fs } from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath, URL } from 'node:url';
import { publicPackageManifestPaths } from './public-packages.mjs';

/** Current repository root resolved independently from the invoking cwd. */
const root = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
/** Generated snapshot consumed by init, Migration and release verification. */
const snapshotPath = path.join(root, 'packages/acplugin/src/ecosystem/versions.json');

/** Read and validate the fixed public package manifest catalog. */
async function publicVersions() {
  /** Prevent a catalog typo from silently reading the same manifest twice. */
  if (new Set(publicPackageManifestPaths).size !== publicPackageManifestPaths.length)
    throw new Error('Public package manifest catalog contains duplicate paths.');
  /** Stable insertion order is the catalog order, not filesystem or locale order. */
  const versions = {};
  for (const relative of publicPackageManifestPaths) {
    /** Public manifest content is the only editable version source. */
    const manifest = JSON.parse(await fs.readFile(path.join(root, relative), 'utf8'));
    if (typeof manifest.name !== 'string' || !manifest.name.startsWith('@tokenroll/')
      || typeof manifest.version !== 'string' || manifest.version.length === 0 || manifest.private === true) {
      throw new Error(`Public package manifest is invalid: ${relative}`);
    }
    if (Object.hasOwn(versions, manifest.name))
      throw new Error(`Public package name is duplicated: ${manifest.name}`);
    versions[manifest.name] = manifest.version;
  }
  return versions;
}

/** Exact generated bytes include stable indentation and one trailing newline. */
const expected = `${JSON.stringify(await publicVersions(), null, 2)}\n`;
/** The command has one explicit mutation mode and one read-only verification mode. */
const mode = process.argv[2];
if (mode === '--write') {
  await fs.writeFile(snapshotPath, expected);
} else if (mode === '--check') {
  const actual = await fs.readFile(snapshotPath, 'utf8').catch(() => '');
  if (actual !== expected)
    throw new Error('Public package version snapshot is stale. Run pnpm run versions:sync.');
} else {
  throw new Error('Usage: sync-ecosystem-versions.mjs --write|--check');
}
